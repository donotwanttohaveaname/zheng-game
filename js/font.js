// characters we substitute before rendering (typography → bitmap-safe)
function fontClean(s) {
  return String(s)
    .replace(/…/g, '...').replace(/[—–]/g, '-').replace(/[’‘]/g, "'")
    .replace(/[“”]/g, '"').replace(/×/g, 'x').replace(/✕/g, 'x');
}

const FontCache = {};
function fontSheet(color) {
  if (FontCache[color]) return FontCache[color];
  const keys = Object.keys(FONT);
  const c = document.createElement('canvas');
  c.width = keys.length * 6; c.height = 7;
  const x = c.getContext('2d');
  x.fillStyle = color;
  keys.forEach((ch, i) => {
    const g = FONT[ch];
    for (let col = 0; col < 5; col++) for (let row = 0; row < 7; row++)
      if (g[col] >> row & 1) x.fillRect(i * 6 + col, row, 1, 1);
  });
  const sheet = { canvas: c, index: {} };
  keys.forEach((ch, i) => sheet.index[ch] = i);
  FontCache[color] = sheet;
  return sheet;
}

function drawText(ctx, str, x, y, color) {
  const s = fontSheet(color || '#f4f0e6');
  str = fontClean(str);
  let cx = x;
  for (const ch of str) {
    const i = s.index[ch];
    if (i !== undefined && ch !== ' ') ctx.drawImage(s.canvas, i * 6, 0, 5, 7, cx, y, 5, 7);
    cx += 6;
  }
  return cx;
}
function textWidth(str) { return fontClean(str).length * 6; }
function drawTextCenter(ctx, str, cx, y, color) { drawText(ctx, str, Math.round(cx - textWidth(str) / 2), y, color); }
function drawTextRight(ctx, str, rx, y, color) { drawText(ctx, str, Math.round(rx - textWidth(str)), y, color); }
// scaled (for Sandal's ever-longer job title: shrinks to fit, per spec appendix A)
function drawTextFit(ctx, str, x, y, maxW, color) {
  const w = textWidth(str);
  if (w <= maxW) { drawText(ctx, str, x, y, color); return; }
  const s = fontSheet(color || '#f4f0e6');
  const off = document.createElement('canvas');
  off.width = w; off.height = 7;
  const ox = off.getContext('2d');
  let cx2 = 0;
  for (const ch of fontClean(str)) {
    const i = s.index[ch];
    if (i !== undefined && ch !== ' ') ox.drawImage(s.canvas, i * 6, 0, 5, 7, cx2, 0, 5, 7);
    cx2 += 6;
  }
  ctx.imageSmoothingEnabled = false;
  ctx.drawImage(off, x, y, maxW, 7);
}

function wrapText(str, cols) {
  cols = cols || 28;
  const out = [];
  fontClean(str).split('\n').forEach(par => {
    const words = par.split(' ');
    let line = '';
    words.forEach(w => {
      while (w.length > cols) { // pathological long word
        if (line) { out.push(line); line = ''; }
        out.push(w.slice(0, cols)); w = w.slice(cols);
      }
      if (!line) line = w;
      else if (line.length + 1 + w.length <= cols) line += ' ' + w;
      else { out.push(line); line = w; }
    });
    out.push(line);
  });
  return out;
}
